import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

async function loadDemo(page: Page) { await page.goto('/'); await page.getByRole('button', { name: 'Завантажити демодані', exact: true }).click() }
const nav = (page: Page, name: string) => page.getByRole('navigation').getByRole('button', { name }).click()

test('глобальний пошук відкриває потрібну сутність, lost/won і період оновлюють KPI', async ({ page }) => {
  await loadDemo(page)
  await page.getByLabel('Глобальний пошук').fill('Айдентика для Коло')
  await page.locator('.search-results').getByRole('button', { name: 'Айдентика для Коло Угода' }).click()
  await expect(page.getByLabel('Назва угоди *')).toHaveValue('Айдентика для Коло')
  await page.getByLabel('Стадія', { exact: true }).selectOption('Втрачено')
  await page.getByRole('button', { name: 'Зберегти', exact: true }).click()
  await expect(page.getByTestId('kpi-open')).toHaveText('14')
  await expect(page.getByTestId('kpi-rate')).toHaveText('67%')
  await page.getByLabel('Період показників').selectOption('month')
  const snapshot = await page.evaluate(() => JSON.parse(localStorage.getItem('dealpilot.data.v1')!))
  const today = new Date().toLocaleDateString('sv-SE')
  const won = snapshot.deals.filter((d: { status: string; closedAt: string | null }) => d.status === 'won' && d.closedAt && new Date(d.closedAt).toLocaleDateString('sv-SE').startsWith(today.slice(0, 7))).length
  await expect(page.getByTestId('kpi-won')).toHaveText(String(won).padStart(2, '0'))
  await page.getByLabel('Валюта показників').selectOption('USD')
  await expect(page.getByTestId('kpi-open')).toHaveText('00')
  await expect(page.getByTestId('kpi-rate')).toHaveText('—')
  await page.getByLabel('Глобальний пошук').fill('Олена')
  await page.locator('.search-results').getByRole('button', { name: /Олена Приклад/ }).click()
  await expect(page.getByLabel('Ім’я *')).toHaveValue('Олена Приклад')
})

test('незалежне завдання, пріоритет, CSV та скидання демо', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Нове завдання', exact: true }).click()
  await page.getByLabel('Назва завдання *').fill('=1+1, "перевірка"')
  await page.getByLabel('Пріоритет', { exact: true }).selectOption('high')
  await page.getByRole('button', { name: 'Зберегти', exact: true }).click()
  await expect(page.locator('.task-row')).toContainText('Високий')
  await page.getByLabel('Виконано: =1+1, "перевірка"', { exact: true }).click()
  await page.getByRole('button', { name: 'Дані та налаштування', exact: true }).click()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Завдання CSV' }).click()])
  expect(readFileSync((await download.path())!, 'utf8')).toContain('"\'=1+1, ""перевірка"""')
  await page.getByRole('button', { name: 'Очистити всі дані', exact: true }).click()
  await page.getByRole('button', { name: 'Скасувати', exact: true }).click()
  await nav(page, 'Завдання')
  await page.getByLabel('Фільтр завдань').selectOption('done')
  await expect(page.locator('.task-row')).toHaveCount(1)
  await page.getByLabel('Виконано: =1+1, "перевірка"', { exact: true }).click()
  await page.getByLabel('Фільтр завдань').selectOption('open')
  await expect(page.locator('.task-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Дані та налаштування', exact: true }).click()
  await page.getByRole('button', { name: 'Очистити всі дані', exact: true }).click()
  await page.getByRole('button', { name: 'Видалити всі дані', exact: true }).click()
  await nav(page, 'Огляд')
  await expect(page.getByTestId('kpi-open')).toHaveText('00')
  await expect(page.getByTestId('kpi-average')).toHaveText('—')
})

test('v1 у браузері мігрує, історична дата залишається невідомою, копія збережена', async ({ page }) => {
  await page.goto('/')
  const original = readFileSync('TEST_DATA/example.json', 'utf8')
  await page.evaluate(raw => localStorage.setItem('dealpilot.data.v1', raw), original)
  await page.reload()
  await expect(page.locator('.metric-note')).toContainText('без дат')
  await page.getByRole('button', { name: 'Нова угода', exact: true }).click()
  await page.getByLabel('Назва угоди *').fill('Після міграції')
  await page.getByLabel('Сума *').fill('100')
  await page.getByRole('button', { name: 'Зберегти', exact: true }).click()
  expect(await page.evaluate(() => localStorage.getItem('dealpilot.backup.v1'))).toBe(original)
  await page.reload()
  await page.getByLabel('Глобальний пошук').fill('Після міграції')
  await expect(page.locator('.search-results')).toContainText('Після міграції')
})

test('сортування, пагінація та всі цільові ширини без прокрутки сторінки', async ({ page }) => {
  await loadDemo(page)
  const failures: string[] = []; page.on('pageerror', error => failures.push(error.message))
  for (const width of [1440, 1280, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (width === 390) {
      await expect(page.getByRole('status')).toHaveCount(0)
      await page.screenshot({ path: 'docs/screenshots/04-overview-mobile.png', fullPage: true, animations: 'disabled' })
    }
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await nav(page, 'Угоди')
  await page.getByRole('button', { name: 'Нова угода', exact: true }).click()
  await page.getByLabel('Назва угоди *').fill('Найбільша угода')
  await page.getByLabel('Сума *').fill('999999')
  await page.getByRole('button', { name: 'Зберегти', exact: true }).click()
  await page.getByRole('button', { name: 'Таблиця угод', exact: true }).click()
  await page.getByLabel('Сортування угод').selectOption('amount')
  await expect(page.locator('tbody tr').first()).toContainText('Найбільша угода')
  await expect(page.locator('tbody tr')).toHaveCount(20)
  await page.getByRole('button', { name: 'Далі →' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  expect(failures).toEqual([])
})
