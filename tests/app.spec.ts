test('експорт, скасування імпорту, пошкоджений JSON і відновлення зв’язків', async ({ page }) => {
  await demo(page); await settings(page)
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Експорт JSON' }).click()])
  const path = await download.path()
  const original = readFileSync(path!, 'utf8')
  const before = await page.evaluate(() => localStorage.getItem('dealpilot.data.v1'))
  await page.getByLabel('Імпорт JSON', { exact: true }).setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{bad') })
  await expect(page.getByRole('alert')).toContainText('Не вдалося прочитати JSON')
  expect(await page.evaluate(() => localStorage.getItem('dealpilot.data.v1'))).toBe(before)
  const missingContact = JSON.parse(original); missingContact.contacts = []
  await page.getByLabel('Імпорт JSON', { exact: true }).setInputFiles({ name: 'broken-link.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(missingContact)) })
  await expect(page.getByRole('alert')).toContainText('відсутній контакт')
  expect(await page.evaluate(() => localStorage.getItem('dealpilot.data.v1'))).toBe(before)
  await page.getByLabel('Імпорт JSON', { exact: true }).setInputFiles(path!)
  await expect(page.getByRole('dialog')).toContainText('Усі поточні локальні дані буде замінено')
  await page.getByRole('button', { name: 'Скасувати' }).click()
  expect(await page.evaluate(() => localStorage.getItem('dealpilot.data.v1'))).toBe(before)
  await page.getByRole('button', { name: 'Очистити всі дані', exact: true }).click()
  await page.getByRole('button', { name: 'Видалити всі дані', exact: true }).click()
  await page.getByLabel('Імпорт JSON', { exact: true }).setInputFiles(path!)
  await page.getByRole('button', { name: 'Замінити локальні дані', exact: true }).click()
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('dealpilot.data.v1')!))
  expect(restored.contacts).toEqual(JSON.parse(original).contacts)
  expect(restored.deals).toEqual(JSON.parse(original).deals)
  expect(restored.tasks).toEqual(JSON.parse(original).tasks)
  expect(restored.history[0].text).toContain('Імпортовано')
})

