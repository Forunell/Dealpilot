test('1440 / 768 / 360: адаптивність, скриншоти й мобільна зміна стадії', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await demo(page)
  await expect(page.getByRole('status')).toHaveCount(0)
  mkdirSync('docs/screenshots', { recursive: true })
  for (const width of [1440, 768, 360]) {
    await page.setViewportSize({ width, height: width === 360 ? 800 : 1000 })
    if (width === 360) await page.getByRole('button', { name: 'Відкрити навігацію' }).click()
    await nav(page, 'Огляд').click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (width === 1440) await page.screenshot({ path: 'docs/screenshots/01-overview-desktop.png', fullPage: true })
    if (width === 360) await page.getByRole('button', { name: 'Відкрити навігацію' }).click()
    await nav(page, 'Угоди').click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (width === 1440) await page.screenshot({ path: 'docs/screenshots/02-kanban-desktop.png', fullPage: true })
    if (width === 360) {
      await page.getByLabel('Стадія: Айдентика для Коло', { exact: true }).selectOption('Пропозиція')
      await expect(page.getByLabel('Стадія: Айдентика для Коло', { exact: true })).toHaveValue('Пропозиція')
      await page.locator('.kanban').evaluate(el => { el.scrollLeft = 0 })
      await expect(page.getByRole('status')).toHaveCount(0)
      await page.screenshot({ path: 'docs/screenshots/03-kanban-mobile.png' })
    }
  }
  expect(errors).toEqual([])
})
